"""Check that every character used by the UI exists in the LVGL CJK font.

The font file is generated by lv_font_conv and keeps the full --symbols list in
its header comment, so the glyph coverage can be verified statically, without
flashing and squinting at the panel.
"""

import re
import sys

FONT = (r"D:\Agent_Work\2026-11-01-12-56-00\portal_guard\managed_components"
        r"\lvgl__lvgl\src\font\lv_font_source_han_sans_sc_16_cjk.c")

# Every string that reaches lv_label_set_text() in ui.c / net_guard.c
STRINGS = [
    "校园网守护",
    "ESP32-S3 . 5min",
    "ONLINE", "AUTH", "LOGIN", "FAILED", "CHECK", "NO WIFI", "OFFLINE", "LINKING",
    "外网正常", "需要认证", "正在登录", "认证失败", "检测外网中",
    "WiFi 已断开", "外网不可达", "正在连接 WiFi",
    "网络", "IP 地址", "重新认证", "下次检测", "运行时长",
    "次", "启动中", "轻触屏幕立即检测",
    "正在检测外网", "已连上 ", "连接 ", "连不上 ",
    "认证中", "认证成功，外网已通", "认证返回成功但外网仍不通",
    "已联网", "被劫持 -> ", "返回登录页（200）", "探不到 Portal",
    "秒后重试", "WiFi 断开 (reason ", "内存不足",
]

src = open(FONT, "r", encoding="utf-8", errors="replace").read(4000)

m = re.search(r"--symbols\s+(.*?)\s+--font", src, re.S)
if not m:
    print("cannot locate --symbols in font header")
    sys.exit(1)

symbols = set(m.group(1))
# ASCII range is included separately by -r 0x20-0x7f
for c in range(0x20, 0x80):
    symbols.add(chr(c))

missing = {}
for s in STRINGS:
    for ch in s:
        if ch not in symbols:
            missing.setdefault(ch, []).append(s)

print("glyph set size : %d" % len(symbols))
print("strings checked: %d" % len(STRINGS))

if not missing:
    print("RESULT: every character is covered")
else:
    print("RESULT: %d missing characters" % len(missing))
    for ch, where in sorted(missing.items()):
        print("  U+%04X %s  <- %s" % (ord(ch), ch, where[0]))
